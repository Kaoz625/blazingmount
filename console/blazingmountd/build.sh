# build.sh - build blazingmountd (the ONE BlazingMount payload) with our libSceAmpr link fork EMBEDDED in it.
#
#   FORK=/path/to/libSceAmpr.sprx PS5_PAYLOAD_SDK=/path/to/ps5-payload-sdk sh build.sh        -> out/blazingmountd.elf   (the console payload)
#   FORK=/path/to/libSceAmpr.sprx HOST=1 sh build.sh                                         -> out/blazingmountd-host  (fake-console test build)
#
# FORK defaults to ../link-fork/prebuilt/libSceAmpr.sprx (build it with ../link-fork/tools/build-fork.sh; it is never committed).
# The fork's bytes go into out/fork_blob.h (generated, not committed) and from there into the payload: a console needs no loose fork file.
# Optional: BM_DEFAULT_HOST=192.168.1.130 (the host's imgserve; /data/blazing/mount.conf still overrides it on a console).
# Optional: BM_REV=<short sha> when building from an exported tree with no git (`git archive <pushed sha>` on the build machine):
#   the payload then logs "blazingmountd 2.8-<sha> start" instead of "2.8-local+dirty" (v2.5 on both consoles logs "2.0-local+dirty").
#
# Install (reboot-surviving): a payload-manager LOCAL SLOT + one autoload line - see ../../install/blazingmount-autoload.md. In a boot list
# it runs unattended with no arguments: it loops and only writes under /data/homebrew, /data/blazing and /data/blz-stage.
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
FORK="${FORK:-$HERE/../link-fork/prebuilt/libSceAmpr.sprx}"
[ -f "$FORK" ] || { echo "no fork at $FORK (set FORK=...)"; exit 1; }
mkdir -p "$HERE/out"
if [ -n "$BM_REV" ]; then
  VERSION="2.8-$BM_REV"
else
  VERSION="2.8-$(git -C "$HERE" rev-parse --short HEAD 2>/dev/null || echo local)$(git -C "$HERE" diff --quiet -- src 2>/dev/null || echo '+dirty')"
fi
python3 -I - "$FORK" "$HERE/out/fork_blob.h" <<'EOF'
import hashlib, sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as fh:
    fh.write("// generated by build.sh from %s - do not commit\n" % sys.argv[1].split("/")[-1])
    fh.write('#define BM_FORK_SHA "%s"\n' % hashlib.sha256(data).hexdigest())
    fh.write("static const unsigned long bm_fork_len = %d;\n" % len(data))
    fh.write("static const unsigned char bm_fork[] = {\n")
    for i in range(0, len(data), 24):
        fh.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
    fh.write("};\n")
EOF
DEFS="-DBM_VERSION=\"$VERSION\""
[ -n "$BM_DEFAULT_HOST" ] && DEFS="$DEFS -DBM_DEFAULT_HOST=\"$BM_DEFAULT_HOST\""
if [ -n "$HOST" ]; then
  ${CC:-cc} -O2 -Wall -Wextra -std=gnu11 $DEFS -I"$HERE/out" -o "$HERE/out/blazingmountd-host" "$HERE/src/blazingmountd.c"
  echo "built: $HERE/out/blazingmountd-host ($VERSION, fork sha256 $(shasum -a 256 "$FORK" | cut -c1-16))"
  exit 0
fi
: "${PS5_PAYLOAD_SDK:?set PS5_PAYLOAD_SDK to your ps5-payload-sdk checkout (or HOST=1 for the test build)}"
CC="${CC:-${PS5_PAYLOAD_SDK}/bin/prospero-clang}"
"$CC" -O2 -Wall -Wextra -std=gnu11 $DEFS -I"$HERE/out" -o "$HERE/out/blazingmountd.elf" "$HERE/src/blazingmountd.c" -lkernel_sys
echo "built: $HERE/out/blazingmountd.elf ($VERSION, fork sha256 $(shasum -a 256 "$FORK" | cut -c1-16))"
