// blazingmountd - BlazingMount's ONE on-console payload: it builds every streaming starter ITSELF.
//
// v2 (23 Oct 2026). The host only LISTS and SERVES files (imgserve, read-only); every decision about a game is made here, so every
// error on a console is attributable to this payload and its log (/data/blazing/blazingmountd.log, mirrored to klog).
//
// Once at boot and then every poll_secs (resident via the payload manager's autoload):
//   1. host = built-in default (BM_DEFAULT_HOST:4451), /data/blazing/mount.conf only as an override (see read_conf)
//   2. GET /games.txt                    every PS5 image the host can serve: key (TID@bytes), tid, size, version, fw, sdk, title
//   3. for each game that is not on this console yet (folder name or title id already present -> skipped) and fits this console's FW:
//        GET /f/<key>                     its file list (size, path)
//        build /data/blz-stage/bm/<Name (TID)>/ with mkgame.py's rules (host/engine/mkgame.py + blazingmount-starter.py):
//          - small files (< 1 MiB), eboot.bin, sce_sys/, sce_module/, prx/, and every .pgm .prx .sprx .elf .self .index .crc: real bytes
//          - every other file >= 1 MiB: a 0-byte placeholder, streamed by the link (largest first, at most 24576)
//          - ampr_emu.index with the REAL sizes when the game has none
//          - fakelib/libSceAmpr.sprx = OUR link fork, EMBEDDED in this payload (+ the game's own fakelib files except its libSceAmpr)
//        write /data/blazing/link/<TID>.cfg, then move the starter into /data/homebrew/ (ShadowMount registers the tile)
//   A game is built once: the state file /data/blazing/blazingmountd.state remembers done / refused / failed (failed: 3 tries max),
//   so nothing is downloaded again in a loop. Games that need a newer FW than this console are refused (backport = phase 2).
//
// It never fetches, cracks, signs, or decrypts anything: the host only serves files the user put there. Content-neutral.
//
// The same source builds on a Mac/Linux host (no __PROSPERO__) for the fake-console test: BM_ROOT=<dir> prefixes every console path,
// so `BM_ROOT=/tmp/x blazingmountd once` builds starters into /tmp/x/data/homebrew from a test imgserve (host/test_console_builder.py).

