// ---------------------------------------------------------------- paths, log
static char g_root[512] = "";           // host test only: prefix for every console path

static const char *P(char *buf, size_t n, const char *path) { snprintf(buf, n, "%s%s", g_root, path); return buf; }

static void logf_(const char *fmt, ...) {
    char msg[2048], line[2200], lp[600];
    va_list ap; va_start(ap, fmt); vsnprintf(msg, sizeof msg, fmt, ap); va_end(ap);
    time_t t = time(NULL); struct tm tm; localtime_r(&t, &tm);
    int n = snprintf(line, sizeof line, "%04d-%02d-%02d %02d:%02d:%02d %s\n", tm.tm_year + 1900, tm.tm_mon + 1, tm.tm_mday,
                     tm.tm_hour, tm.tm_min, tm.tm_sec, msg);
    int fd = open(P(lp, sizeof lp, LOG_PATH), O_WRONLY | O_CREAT | O_APPEND, 0644);
    if (fd >= 0) { (void)!write(fd, line, n); close(fd); }
#ifdef __PROSPERO__
    klog_printf("[blazingmountd] %s\n", msg);
#else
    if (getenv("BM_VERBOSE")) fputs(line, stderr);
#endif
}

static int exists(const char *p) { struct stat st; return stat(p, &st) == 0; }

static void makedirs(const char *path) {
    char tmp[1700]; strncpy(tmp, path, sizeof tmp - 1); tmp[sizeof tmp - 1] = 0;
    for (char *p = tmp + 1; *p; p++)
        if (*p == '/') { *p = 0; mkdir(tmp, 0755); *p = '/'; }
    mkdir(tmp, 0755);
}

static void parent_dirs(const char *file) {
    char d[1700]; strncpy(d, file, sizeof d - 1); d[sizeof d - 1] = 0;
    char *s = strrchr(d, '/'); if (s && s != d) { *s = 0; makedirs(d); }
}

static void rm_rf(const char *path) {
    struct stat st;
    if (lstat(path, &st) != 0) return;
    if (S_ISDIR(st.st_mode)) {
        DIR *d = opendir(path);
        if (d) {
            struct dirent *e;
            while ((e = readdir(d))) {
                if (!strcmp(e->d_name, ".") || !strcmp(e->d_name, "..")) continue;
                char c[1700]; snprintf(c, sizeof c, "%s/%s", path, e->d_name); rm_rf(c);
            }
            closedir(d);
        }
        rmdir(path);
    } else unlink(path);
}

static int write_all(int fd, const void *b, size_t n) {
    const char *p = b;
    while (n) { ssize_t w = write(fd, p, n); if (w <= 0) return -1; p += w; n -= (size_t)w; }
    return 0;
}

static int write_file(const char *path, const void *data, size_t n) {
    parent_dirs(path);
    int fd = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0644);
    if (fd < 0) return -1;
    int r = write_all(fd, data, n);
    close(fd);
    return r;
}

// ---------------------------------------------------------------- tiny HTTP/1.0 client
static void url_path(char *out, size_t n, const char *raw) {        // percent-encode everything but unreserved and '/'
    static const char hx[] = "0123456789ABCDEF";
    size_t o = 0;
    for (const unsigned char *p = (const unsigned char *)raw; *p && o + 4 < n; p++) {
        unsigned char c = *p;
        if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || strchr("-._~/@", c)) out[o++] = (char)c;
        else { out[o++] = '%'; out[o++] = hx[c >> 4]; out[o++] = hx[c & 15]; }
    }
    out[o] = 0;
}

// GET path. Body goes to outfd (>= 0) or into *mem (malloc'd, NUL-terminated). Returns body bytes, or -1 (connect/IO), -2 (non-2xx).
static long long http_get(const char *host, int port, const char *path, int outfd, char **mem, int timeout_s, int *status_out) {
    if (status_out) *status_out = 0;
    int s = socket(AF_INET, SOCK_STREAM, 0);
    if (s < 0) return -1;
    struct timeval tv = { timeout_s, 0 };
    setsockopt(s, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof tv);
    setsockopt(s, SOL_SOCKET, SO_SNDTIMEO, &tv, sizeof tv);
    struct sockaddr_in a; memset(&a, 0, sizeof a);
    a.sin_family = AF_INET; a.sin_port = htons((unsigned short)port);
    if (inet_pton(AF_INET, host, &a.sin_addr) != 1 || connect(s, (struct sockaddr *)&a, sizeof a) < 0) { close(s); return -1; }
    char enc[3000], req[3300];
    url_path(enc, sizeof enc, path);
    int rl = snprintf(req, sizeof req, "GET %s HTTP/1.0\r\nHost: %s\r\nConnection: close\r\n\r\n", enc, host);
    if (write_all(s, req, (size_t)rl) != 0) { close(s); return -1; }

    static char buf[1 << 20];
    size_t have = 0; long body_off = -1;
    while (body_off < 0) {                                              // read the headers
        if (have >= sizeof buf) { close(s); return -1; }
        ssize_t n = read(s, buf + have, sizeof buf - have);
        if (n <= 0) { close(s); return -1; }
        have += (size_t)n;
        for (size_t i = 0; i + 4 <= have; i++)
            if (buf[i] == '\r' && buf[i + 1] == '\n' && buf[i + 2] == '\r' && buf[i + 3] == '\n') { body_off = (long)i + 4; break; }
    }
    int status = (have > 12 && !strncmp(buf, "HTTP/1.", 7)) ? atoi(buf + 9) : 0;
    if (status_out) *status_out = status;
    if (status < 200 || status > 299) { close(s); return -2; }
    long long clen = -1;
    for (long i = 0; i < body_off; i++)
        if ((buf[i] == '\n') && !strncasecmp(buf + i + 1, "Content-Length:", 15)) { clen = atoll(buf + i + 16); break; }

    size_t cap = 0, len = 0; char *m = NULL;
    long long total = 0;
    size_t first = have - (size_t)body_off;
    const char *chunk = buf + body_off; size_t clen_now = first;
    for (;;) {
        if (clen_now) {
            if (outfd >= 0) { if (write_all(outfd, chunk, clen_now) != 0) { close(s); free(m); return -1; } }
            else {
                if (len + clen_now + 1 > cap) { cap = (len + clen_now + 1) * 2; char *nm = realloc(m, cap); if (!nm) { close(s); free(m); return -1; } m = nm; }
                memcpy(m + len, chunk, clen_now); len += clen_now;
            }
            total += (long long)clen_now;
        }
        if (clen >= 0 && total >= clen) break;
        ssize_t n = read(s, buf, sizeof buf);
        if (n < 0) { close(s); free(m); return -1; }
        if (n == 0) break;
        chunk = buf; clen_now = (size_t)n;
    }
    close(s);
    if (clen >= 0 && total != clen) { free(m); return -1; }        // cut short
    if (outfd < 0) { if (!m) m = malloc(1); m[len] = 0; *mem = m; }
    return total;
}

// ---------------------------------------------------------------- settings (built-in defaults; mount.conf overrides)
#define MAX_LIST 256
typedef struct {
    char host[64]; int port;
    int fw_override;                 // console FW in hundredths (1360 = 13.60), 0 = ask the kernel
    long long max_starter_mb, min_free_mb, big_starter_mb, big_free_mb;
    int poll_secs;
    int n_only, n_skip, n_first;
    char only[MAX_LIST][40], skip[MAX_LIST][40], first[MAX_LIST][40];
} conf_t;

static int fw_hundredths(const char *s) {                           // "13.60" -> 1360, "" -> 0
    if (!s || !*s) return 0;
    int maj = atoi(s); const char *d = strchr(s, '.');
    int mn = d ? atoi(d + 1) : 0;
    if (d && strlen(d + 1) == 1) mn *= 10;
    return maj * 100 + mn;
}

// mount.conf (optional), one setting per line; '#' comments:
//   host 192.168.1.130 | port 4451 | fw 13.60 | only <TID or TID@bytes> | skip <TID or TID@bytes>
//   first <TID or TID@bytes>   built before every other game, in the order listed (e.g. the games this console had before a wipe)
//   max_starter_mb 2048 | min_free_mb 51200 | poll_secs 600
//   big_starter_mb 12000 | big_free_mb 204800   a starter may be up to big_starter_mb when /data has >= big_free_mb free
//                                              (GoT 9.8 GB, CoD 3.6 GB: Markus wants them back, 23 Oct)
// The v1 one-line form "<ip> <port>" pointed at the old catalog server: its ip is kept, its port ignored (imgserve is :4451).
static void read_conf(conf_t *c) {
    memset(c, 0, sizeof *c);
    strcpy(c->host, BM_DEFAULT_HOST); c->port = BM_DEFAULT_PORT;
    c->max_starter_mb = 2048; c->min_free_mb = 50 * 1024; c->poll_secs = 600;
    c->big_starter_mb = 12000; c->big_free_mb = 200 * 1024;
    char p[600]; int fd = open(P(p, sizeof p, CONF_PATH), O_RDONLY);
    if (fd < 0) return;
    char txt[8192]; ssize_t n = read(fd, txt, sizeof txt - 1); close(fd);
    if (n <= 0) return;
    txt[n] = 0;
    char *save = NULL;
    for (char *line = strtok_r(txt, "\n", &save); line; line = strtok_r(NULL, "\n", &save)) {
        char k[64] = "", v[256] = "";
        if (line[0] == '#' || sscanf(line, "%63s %255s", k, v) < 1) continue;
        struct in_addr ia;
        if (inet_pton(AF_INET, k, &ia) == 1) {                       // v1 "<ip> <port>"
            strncpy(c->host, k, sizeof c->host - 1);
            static int said = 0;
            if (!said++) logf_("mount.conf: v1 line '%s %s': host %s kept, port %s ignored (imgserve :%d)", k, v, k, v, c->port);
        } else if (!strcmp(k, "host") && v[0]) strncpy(c->host, v, sizeof c->host - 1);
        else if (!strcmp(k, "port")) c->port = atoi(v);
        else if (!strcmp(k, "fw")) c->fw_override = fw_hundredths(v);
        else if (!strcmp(k, "only") && c->n_only < MAX_LIST) strncpy(c->only[c->n_only++], v, 39);
        else if (!strcmp(k, "skip") && c->n_skip < MAX_LIST) strncpy(c->skip[c->n_skip++], v, 39);
        else if (!strcmp(k, "first") && c->n_first < MAX_LIST) strncpy(c->first[c->n_first++], v, 39);
        else if (!strcmp(k, "max_starter_mb")) c->max_starter_mb = atoll(v);
        else if (!strcmp(k, "min_free_mb")) c->min_free_mb = atoll(v);
        else if (!strcmp(k, "big_starter_mb")) c->big_starter_mb = atoll(v);
        else if (!strcmp(k, "big_free_mb")) c->big_free_mb = atoll(v);
        else if (!strcmp(k, "poll_secs") && atoi(v) >= 30) c->poll_secs = atoi(v);
        else logf_("mount.conf: unknown setting '%s' ignored", k);
    }
}

static int listed(char list[][40], int n, const char *key, const char *tid) {
    for (int i = 0; i < n; i++) if (!strcmp(list[i], key) || !strcmp(list[i], tid)) return 1;
    return 0;
}

static int console_fw(const conf_t *c) {
    if (c->fw_override) return c->fw_override;
#ifdef __PROSPERO__
    uint32_t v = kernel_get_fw_version();                           // BCD, e.g. 0x13600000 -> 13.60
    int maj = ((v >> 28) & 15) * 10 + ((v >> 24) & 15), mn = ((v >> 20) & 15) * 10 + ((v >> 16) & 15);
    static int said = 0;
    if (!said) { logf_("console FW raw 0x%08x -> %d.%02d", v, maj, mn); said = 1; }
    return maj * 100 + mn;
#else
    return 0;                                                        // host test: no FW limit unless mount.conf says
#endif
}

static long long free_mb(const char *path) {
    struct statfs sf;
    if (statfs(path, &sf) != 0) return -1;
    return (long long)sf.f_bavail * (long long)sf.f_bsize / (1024 * 1024);
}

// ---------------------------------------------------------------- state: one line per image key: key \t status \t tries \t reason
#define MAX_STATE 2048
typedef struct { char key[48]; char status[12]; int tries; char reason[240]; } st_t;
static st_t g_st[MAX_STATE]; static int g_nst;

static void state_load(void) {
    g_nst = 0;
    char p[600], *mem = NULL; int fd = open(P(p, sizeof p, STATE_PATH), O_RDONLY);
    if (fd < 0) return;
    struct stat sb; if (fstat(fd, &sb) != 0 || sb.st_size <= 0) { close(fd); return; }
    mem = malloc((size_t)sb.st_size + 1);
    ssize_t n = read(fd, mem, (size_t)sb.st_size); close(fd);
    if (n <= 0) { free(mem); return; }
    mem[n] = 0;
    char *save = NULL;
    for (char *l = strtok_r(mem, "\n", &save); l && g_nst < MAX_STATE; l = strtok_r(NULL, "\n", &save)) {
        st_t *s = &g_st[g_nst]; memset(s, 0, sizeof *s);
        char *f[4] = {0}; int k = 0; char *q = l; f[k++] = q;
        while (*q && k < 4) { if (*q == '\t') { *q = 0; f[k++] = q + 1; } q++; }
        if (k < 3) continue;
        strncpy(s->key, f[0], sizeof s->key - 1); strncpy(s->status, f[1], sizeof s->status - 1);
        s->tries = atoi(f[2]); if (k > 3) strncpy(s->reason, f[3], sizeof s->reason - 1);
        g_nst++;
    }
    free(mem);
}

static void state_save(void) {
    char p[600], t[640]; P(p, sizeof p, STATE_PATH); snprintf(t, sizeof t, "%s.tmp", p);
    parent_dirs(p);
    int fd = open(t, O_WRONLY | O_CREAT | O_TRUNC, 0644);
    if (fd < 0) return;
    for (int i = 0; i < g_nst; i++) {
        char l[400]; int n = snprintf(l, sizeof l, "%s\t%s\t%d\t%s\n", g_st[i].key, g_st[i].status, g_st[i].tries, g_st[i].reason);
        write_all(fd, l, (size_t)n);
    }
    close(fd);
    rename(t, p);
}

static st_t *state_get(const char *key) {
    for (int i = 0; i < g_nst; i++) if (!strcmp(g_st[i].key, key)) return &g_st[i];
    return NULL;
}

static void state_set(const char *key, const char *status, const char *reason) {
    st_t *s = state_get(key);
    if (!s) { if (g_nst >= MAX_STATE) return; s = &g_st[g_nst++]; memset(s, 0, sizeof *s); strncpy(s->key, key, sizeof s->key - 1); }
    if (!strcmp(status, "failed")) s->tries++;
    strncpy(s->status, status, sizeof s->status - 1); s->status[sizeof s->status - 1] = 0;
    snprintf(s->reason, sizeof s->reason, "%s", reason ? reason : "");
    for (char *q = s->reason; *q; q++) if (*q == '\t' || *q == '\n') *q = ' ';
    state_save();
}

// ---------------------------------------------------------------- title ids already on this console
#define MAX_PRESENT 1024
static char g_present[MAX_PRESENT][10]; static int g_npresent;

static void tids_in(const char *s) {                                  // every PPSA12345 / CUSA12345 in a string
    for (const char *q = s; q[0]; q++) {
        if ((!strncmp(q, "PPSA", 4) || !strncmp(q, "CUSA", 4))) {
            int ok = 1; for (int i = 4; i < 9; i++) if (q[i] < '0' || q[i] > '9') { ok = 0; break; }
            if (ok && g_npresent < MAX_PRESENT) { memcpy(g_present[g_npresent], q, 9); g_present[g_npresent][9] = 0; g_npresent++; q += 8; }
        }
    }
}

// A game is "present" when any folder or image under the places ShadowMount scans carries its title id: in its name, or in its
// sce_sys/param.json. A starter must never be added for a game the console already has (two tiles, one title id).
static void scan_present(void) {
    g_npresent = 0;
    static const char *roots[] = { "/data/homebrew", "/mnt/ext0/homebrew", "/mnt/ext1/homebrew", "/mnt/usb0/homebrew", "/mnt/usb1/homebrew",
                                   "/mnt/usb2/homebrew", "/mnt/usb3/homebrew", "/mnt/ext0", "/mnt/ext1", "/mnt/usb0", "/mnt/usb1", 0 };
    for (int r = 0; roots[r]; r++) {
        char rp[600]; DIR *d = opendir(P(rp, sizeof rp, roots[r]));
        if (!d) continue;
        struct dirent *e;
        while ((e = readdir(d))) {
            if (e->d_name[0] == '.') continue;
            tids_in(e->d_name);
            char pj[1400]; snprintf(pj, sizeof pj, "%s/%s/sce_sys/param.json", rp, e->d_name);
            int fd = open(pj, O_RDONLY);
            if (fd < 0) continue;
            char b[4096]; ssize_t n = read(fd, b, sizeof b - 1); close(fd);
            if (n <= 0) continue;
            b[n] = 0;
            char *t = strstr(b, "\"titleId\"");
            if (t) { char one[64]; snprintf(one, sizeof one, "%.40s", t); tids_in(one); }
        }
        closedir(d);
    }
}

static int tid_present(const char *tid) {
    for (int i = 0; i < g_npresent; i++) if (!strcmp(g_present[i], tid)) return 1;
    return 0;
}

// ---------------------------------------------------------------- ampr_emu.index (AMPRIDX3), exactly host/engine/amprindex.build()
typedef struct { const char *path; size_t plen; long long size; size_t blob_off; int order; } ix_t;

static int key_cmp(const char *a, size_t al, const char *b, size_t bl) {
    size_t n = al < bl ? al : bl;
    for (size_t i = 0; i < n; i++) {
        unsigned char x = (unsigned char)a[i], y = (unsigned char)b[i];
        if (x == '\\') x = '/'; if (y == '\\') y = '/';
        if (x >= 'A' && x <= 'Z') x += 32; if (y >= 'A' && y <= 'Z') y += 32;
        if (x != y) return x < y ? -1 : 1;
    }
    return al < bl ? -1 : (al > bl ? 1 : 0);
}
static int ix_cmp(const void *pa, const void *pb) {
    const ix_t *a = pa, *b = pb;
    int c = key_cmp(a->path, a->plen, b->path, b->plen);
    return c ? c : (a->order - b->order);                            // stable, like Python's sort
}
static uint64_t fnv_key(const char *p, size_t n) {
    uint64_t h = 1469598103934665603ULL;
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)p[i];
        if (c == '\\') c = '/';
        if (c >= 'A' && c <= 'Z') c += 32;
        h ^= c; h *= 1099511628211ULL;
    }
    return h ? h : 1;
}
static void put32(unsigned char *b, uint32_t v) { for (int i = 0; i < 4; i++) b[i] = (unsigned char)(v >> (8 * i)); }
static void put64(unsigned char *b, uint64_t v) { for (int i = 0; i < 8; i++) b[i] = (unsigned char)(v >> (8 * i)); }

// paths[i] = "/app0/<rel>" (blob order), sizes[i]; mtime 0. Writes the index to `out`. Returns 0 on success.
static int write_ampr_index(const char *out, char **paths, long long *sizes, int n) {
    ix_t *ix = calloc((size_t)(n ? n : 1), sizeof *ix);
    size_t blob = 0;
    for (int i = 0; i < n; i++) { ix[i].path = paths[i]; ix[i].plen = strlen(paths[i]); ix[i].size = sizes[i]; ix[i].blob_off = blob; ix[i].order = i; blob += ix[i].plen + 1; }
    qsort(ix, (size_t)n, sizeof *ix, ix_cmp);
    uint64_t slots = 2; while (slots < (uint64_t)2 * (uint64_t)n) slots <<= 1;
    size_t path_off = 48 + (size_t)24 * (size_t)n, hash_off = (path_off + blob + 7) & ~(size_t)7;
    size_t total = hash_off + (size_t)slots * 16;
    unsigned char *b = calloc(1, total);
    if (!b) { free(ix); return -1; }
    memcpy(b, "AMPRIDX3", 8); put32(b + 8, 3); put32(b + 12, 24); put64(b + 16, (uint64_t)n); put64(b + 24, blob);
    put64(b + 32, hash_off); put32(b + 40, 16); put32(b + 44, (uint32_t)slots);
    for (int i = 0; i < n; i++) {
        unsigned char *r = b + 48 + 24 * (size_t)i;
        put32(r, (uint32_t)ix[i].blob_off); put32(r + 4, (uint32_t)ix[i].plen); put64(r + 8, (uint64_t)ix[i].size); put64(r + 16, 0);
    }
    for (int i = 0; i < n; i++) memcpy(b + path_off + ix[i].blob_off, ix[i].path, ix[i].plen + 1);
    uint64_t mask = slots - 1;
    for (int i = 0; i < n; i++) {
        uint64_t h = fnv_key(ix[i].path, ix[i].plen), pos = h & mask; int dup = 0;
        for (;;) {
            unsigned char *sl = b + hash_off + pos * 16;
            uint32_t ip1 = (uint32_t)sl[8] | ((uint32_t)sl[9] << 8) | ((uint32_t)sl[10] << 16) | ((uint32_t)sl[11] << 24);
            if (!ip1) break;
            uint64_t sh = 0; for (int k = 7; k >= 0; k--) sh = (sh << 8) | sl[k];
            if (sh == h) { sl[12] |= 1; dup = 1; }
            pos = (pos + 1) & mask;
        }
        unsigned char *sl = b + hash_off + pos * 16;
        put64(sl, h); put32(sl + 8, (uint32_t)i + 1); put32(sl + 12, dup ? 1 : 0);
    }
    int r = write_file(out, b, total);
    free(b); free(ix);
    return r;
}

// ---------------------------------------------------------------- one game
typedef struct { char *path; long long size; int remote; } gf_t;

static int ends_with(const char *s, const char *suf, int nocase) {
    size_t a = strlen(s), b = strlen(suf);
    if (b > a) return 0;
    return nocase ? !strcasecmp(s + a - b, suf) : !strcmp(s + a - b, suf);
}
static int starts(const char *s, const char *p) { return !strncmp(s, p, strlen(p)); }

// mkgame.KEEP_LOCAL_EXT (case as mkgame) + blazingmount-starter.MODULE_EXT (any case)
static int keep_local(const char *p) {
    static const char *ext[] = { ".pgm", ".prx", ".sprx", ".elf", ".self", ".index", ".crc", 0 };
    static const char *mod[] = { ".prx", ".sprx", ".elf", ".self", 0 };
    for (int i = 0; ext[i]; i++) if (ends_with(p, ext[i], 0)) return 1;
    for (int i = 0; mod[i]; i++) if (ends_with(p, mod[i], 1)) return 1;
    return 0;
}

static int remote_cmp(const void *a, const void *b) {               // size desc, then list order (stable)
    const gf_t *x = *(gf_t *const *)a, *y = *(gf_t *const *)b;
    if (x->size != y->size) return x->size > y->size ? -1 : 1;
    return x < y ? -1 : (x > y);
}

static int file_has(const char *path, const char *needle) {
    int fd = open(path, O_RDONLY); if (fd < 0) return 0;
    static char b[1 << 20]; size_t nl = strlen(needle), keep = 0; int hit = 0;
    for (;;) {
        ssize_t n = read(fd, b + keep, sizeof b - keep);
        if (n <= 0) break;
        size_t len = keep + (size_t)n;
        for (size_t i = 0; i + nl <= len; i++) if (b[i] == needle[0] && !memcmp(b + i, needle, nl)) { hit = 1; break; }
        if (hit) break;
        keep = nl - 1 < len ? nl - 1 : len;
        memmove(b, b + len - keep, keep);
    }
    close(fd);
    return hit;
}

static int fetch_to(const conf_t *c, const char *key, const char *rel, const char *dst, long long want) {
    char url[2200]; snprintf(url, sizeof url, "/t/%s/%s", key, rel);
    for (int t = 1; t <= 3; t++) {
        parent_dirs(dst);
        int fd = open(dst, O_WRONLY | O_CREAT | O_TRUNC, 0644);
        if (fd < 0) { logf_("  cannot create %s (errno %d)", dst, errno); return -1; }
        int st = 0;
        long long n = http_get(c->host, c->port, url, fd, NULL, 60, &st);
        close(fd);
        if (n == want) return 0;
        logf_("  fetch %s try %d: got %lld of %lld bytes (http %d)", rel, t, n, want, st);
        sleep(2 * t);
    }
    return -1;
}

typedef struct { char key[48], tid[16], version[32], fw[16], title[256]; long long size; } game_t;

// Builds one starter. Returns 0 done, 1 refused (reason), -1 failed (reason).
static int build_game(const conf_t *c, const game_t *g, int cfw, char *reason, size_t rn) {
    char name[400], title[300];
    snprintf(title, sizeof title, "%s", g->title[0] ? g->title : g->tid);
    {   // mkgame: name.replace("/", " ").replace(":", "").strip()
        char t2[300]; size_t o = 0;
        for (const char *q = title; *q && o + 1 < sizeof t2; q++) { if (*q == ':') continue; t2[o++] = (*q == '/') ? ' ' : *q; }
        t2[o] = 0;
        char *s = t2; while (*s == ' ' || *s == '\t') s++;
        size_t L = strlen(s); while (L && (s[L - 1] == ' ' || s[L - 1] == '\t')) s[--L] = 0;
        snprintf(name, sizeof name, "%s (%s)", s, g->tid);
    }
    char dest[900], hb[600]; snprintf(dest, sizeof dest, "%s/%s", P(hb, sizeof hb, HOMEBREW_DIR), name);
    if (exists(dest)) { snprintf(reason, rn, "folder already there"); return 0; }

    // 1) the file list
    char url[200], *lst = NULL; int st = 0;
    snprintf(url, sizeof url, "/f/%s", g->key);
    long long ln = http_get(c->host, c->port, url, -1, &lst, 300, &st);
    if (ln < 0) { snprintf(reason, rn, "file list %s failed (http %d)", url, st); return -1; }
    int cap = 1024, n = 0; gf_t *f = malloc(sizeof *f * (size_t)cap);
    char *save = NULL;
    for (char *l = strtok_r(lst, "\n", &save); l; l = strtok_r(NULL, "\n", &save)) {
        char *tab = strchr(l, '\t'); if (!tab) continue;
        *tab = 0;
        if (starts(tab + 1, "decrypted/")) continue;                 // mkgame skips the dumper's decrypted/ copies
        if (n == cap) { cap *= 2; f = realloc(f, sizeof *f * (size_t)cap); }
        f[n].size = atoll(l); f[n].path = tab + 1; f[n].remote = 0; n++;
    }
    // 2) which files stream: >= 1 MiB, not eboot.bin / sce_sys/ / sce_module/ / prx/ / fakelib*, not a keep-local type; largest first
    gf_t **big = malloc(sizeof *big * (size_t)(n ? n : 1)); int nb = 0, has_index = 0, has_eboot = 0;
    long long total = 0;
    for (int i = 0; i < n; i++) {
        total += f[i].size;
        if (!strcmp(f[i].path, "ampr_emu.index")) has_index = 1;
        if (!strcmp(f[i].path, "eboot.bin")) has_eboot = 1;
        if (f[i].size >= MIN_REMOTE_BYTES && strcmp(f[i].path, "eboot.bin") && !starts(f[i].path, "sce_sys/") && !starts(f[i].path, "sce_module/")
            && !starts(f[i].path, "prx/") && !starts(f[i].path, "fakelib") && !keep_local(f[i].path)) big[nb++] = &f[i];
    }
    qsort(big, (size_t)nb, sizeof *big, remote_cmp);
    int nr = nb < MAX_REMOTE ? nb : MAX_REMOTE;
    long long remote_bytes = 0;
    for (int i = 0; i < nr; i++) { big[i]->remote = 1; remote_bytes += big[i]->size; }
    long long starter_bytes = total - remote_bytes;
    int rc = -1;
    char stage[900], sp[600];
    snprintf(stage, sizeof stage, "%s/%s", P(sp, sizeof sp, STAGE_DIR), name);
    if (!has_eboot) { snprintf(reason, rn, "no eboot.bin in the image"); rc = 1; goto out; }
    char dp[600]; long long fm = free_mb(P(dp, sizeof dp, "/data"));
    long long scap = c->max_starter_mb;                               // a bigger starter is fine on a console with lots of room
    if (scap > 0 && c->big_starter_mb > scap && fm >= c->big_free_mb) scap = c->big_starter_mb;
    if (scap > 0 && starter_bytes > scap * 1000000LL) {
        snprintf(reason, rn, "starter would be %.1f GB (limit %lld MB with %lld MB free on /data; %lld MB when >= %lld MB free)",
                 starter_bytes / 1e9, scap, fm, c->big_starter_mb, c->big_free_mb);
        rc = 1; goto out;
    }
    if (fm >= 0 && fm - starter_bytes / (1024 * 1024) < c->min_free_mb) {
        snprintf(reason, rn, "not enough space: %lld MB free, starter %lld MB, floor %lld MB", fm, starter_bytes / (1024 * 1024), c->min_free_mb);
        rc = -1; goto out;
    }
    logf_("build %s [%s] v%s FW %s: %d files, %d streamed (%.1f GB), starter %.2f GB (cap %lld MB, /data free %lld MB), %s", name, g->key, g->version, g->fw, n, nr,
          remote_bytes / 1e9, starter_bytes / 1e9, scap, fm, has_index ? "own ampr_emu.index" : "ampr_emu.index made here");

    // 3) stage: eboot first (fail fast when the game cannot stream), then everything else
    rm_rf(stage);
    makedirs(stage);
    char dst[2400];
    snprintf(dst, sizeof dst, "%s/eboot.bin", stage);
    long long eb = 0; for (int i = 0; i < n; i++) if (!strcmp(f[i].path, "eboot.bin")) eb = f[i].size;
    if (fetch_to(c, g->key, "eboot.bin", dst, eb) != 0) { snprintf(reason, rn, "eboot.bin download failed"); goto out; }
    if (!file_has(dst, "libSceAmpr.prx")) {
        snprintf(reason, rn, "CANNOT STREAM: the eboot does not load libSceAmpr, so our link never runs in this game"); rc = 1; goto out;
    }
    long long got = 0; int nfiles = 0;
    for (int i = 0; i < n; i++) {
        if (!strcmp(f[i].path, "eboot.bin") || starts(f[i].path, "fakelib/")) continue;
        snprintf(dst, sizeof dst, "%s/%s", stage, f[i].path);
        if (f[i].remote) { parent_dirs(dst); if (write_file(dst, "", 0) != 0) { snprintf(reason, rn, "cannot create %s", f[i].path); goto out; } continue; }
        if (fetch_to(c, g->key, f[i].path, dst, f[i].size) != 0) { snprintf(reason, rn, "download failed: %s", f[i].path); goto out; }
        got += f[i].size; nfiles++;
        if (nfiles % 5000 == 0) logf_("  %d files, %.2f GB so far", nfiles, got / 1e9);
    }
    // 4) ampr_emu.index with the real sizes when the game has none
    if (!has_index) {
        char **pp = malloc(sizeof *pp * (size_t)(n ? n : 1)); long long *ss = malloc(sizeof *ss * (size_t)(n ? n : 1)); int k = 0;
        for (int i = 0; i < n; i++) {
            if (starts(f[i].path, "fakelib/")) continue;
            size_t L = strlen(f[i].path) + 7; pp[k] = malloc(L); snprintf(pp[k], L, "/app0/%s", f[i].path); ss[k] = f[i].size; k++;
        }
        snprintf(dst, sizeof dst, "%s/ampr_emu.index", stage);
        int r = write_ampr_index(dst, pp, ss, k);
        for (int i = 0; i < k; i++) free(pp[i]);
        free(pp); free(ss);
        if (r != 0) { snprintf(reason, rn, "cannot write ampr_emu.index"); goto out; }
    }
    // 5) fakelib: our embedded fork as libSceAmpr.sprx + the game's own fakelib files (flattened, minus its libSceAmpr)
    snprintf(dst, sizeof dst, "%s/fakelib/libSceAmpr.sprx", stage);
    if (write_file(dst, bm_fork, bm_fork_len) != 0) { snprintf(reason, rn, "cannot write the fork"); goto out; }
    for (int i = 0; i < n; i++) {
        if (!starts(f[i].path, "fakelib/")) continue;
        const char *base = strrchr(f[i].path, '/') + 1;
        if (!strcmp(base, "libSceAmpr.sprx")) continue;
        snprintf(dst, sizeof dst, "%s/fakelib/%s", stage, base);
        if (fetch_to(c, g->key, f[i].path, dst, f[i].size) != 0) { snprintf(reason, rn, "download failed: %s", f[i].path); goto out; }
    }
    // 6) the link config, BEFORE the folder appears (ShadowMount may register the tile at once)
    {
        long long whole = (remote_bytes + (1 << 20) - 1) >> 20, dc = whole < 2048 ? 2048 : (whole > 16384 ? 16384 : whole);
        size_t cap2 = 4096 + (size_t)nr * 300; char *cfg = malloc(cap2); size_t o = 0;
        o += (size_t)snprintf(cfg + o, cap2 - o, "# blazingmountd %s v%s: %s, %d files read from %s (%.1f GB)\nmode remote\nserver %s %d\nbase /t/%s\n",
                              BM_VERSION, g->version, name, nr, c->host, remote_bytes / 1e9, c->host, c->port, g->key);
        for (int i = 0; i < nr; i++) o += (size_t)snprintf(cfg + o, cap2 - o, "file %lld %s\n", big[i]->size, big[i]->path);
        o += (size_t)snprintf(cfg + o, cap2 - o, "block_kb 256\ncache_mb 32\nconns 4\nasync 1\ntimeout_ms 8000\nstats_s 2\nlog_first 60\n"
                              "trace_opens 100\ntrace_io 60\ntrace_apr 60\ndisk_cache_mb %lld\n", dc);
        char lp[600], cfgp[700], tmp[720];
        snprintf(cfgp, sizeof cfgp, "%s/%s.cfg", P(lp, sizeof lp, LINK_DIR), g->tid);
        snprintf(tmp, sizeof tmp, "%s.tmp", cfgp);
        makedirs(lp);
        int w = write_file(tmp, cfg, o);
        free(cfg);
        if (w != 0 || rename(tmp, cfgp) != 0) { snprintf(reason, rn, "cannot write %s (errno %d)", cfgp, errno); goto out; }
    }
    // 7) into the scanned homebrew dir
    makedirs(hb);
    if (rename(stage, dest) != 0) { snprintf(reason, rn, "move into %s failed (errno %d)", dest, errno); goto out; }
    snprintf(reason, rn, "%s: %d files local (%.2f GB), %d streamed (%.1f GB), fork %.12s", name, nfiles + 1, starter_bytes / 1e9, nr,
             remote_bytes / 1e9, BM_FORK_SHA);
    rc = 0;
out:
    if (rc != 0) rm_rf(stage);                                       // never leave half a starter behind
    free(big); free(f); free(lst);
    (void)cfw;
    return rc;
}

// ---------------------------------------------------------------- one pass over the host's games
static int sync_once(void) {
    conf_t c; read_conf(&c);
    int cfw = console_fw(&c);
    char *txt = NULL; int st = 0;
    long long n = http_get(c.host, c.port, "/games.txt", -1, &txt, 300, &st);
    if (n < 0) { logf_("games list http://%s:%d/games.txt failed (http %d)", c.host, c.port, st); return -1; }
    state_load();
    scan_present();
    int listed_n = 0, present = 0, built = 0, refused = 0, failed = 0, known = 0;
    static game_t rows[2048]; int nrows = 0;
    char *save = NULL;
    for (char *l = strtok_r(txt, "\n", &save); l && nrows < 2048; l = strtok_r(NULL, "\n", &save)) {
        if (l[0] == '#' || !l[0]) continue;
        char *fld[7] = {0}; int k = 0; char *q = l; fld[k++] = q;
        while (*q && k < 7) { if (*q == '\t') { *q = 0; fld[k++] = q + 1; } q++; }
        if (k < 7) continue;
        game_t *g = &rows[nrows++]; memset(g, 0, sizeof *g);
        snprintf(g->key, sizeof g->key, "%s", fld[0]); snprintf(g->tid, sizeof g->tid, "%s", fld[1]); g->size = atoll(fld[2]);
        snprintf(g->version, sizeof g->version, "%s", fld[3]); snprintf(g->fw, sizeof g->fw, "%s", fld[4]);
        snprintf(g->title, sizeof g->title, "%s", fld[6]);
        char *cr = strchr(g->title, '\r'); if (cr) *cr = 0;
    }
    listed_n = nrows;
    // the order: every 'first' entry (in mount.conf order), then the rest in the host's order
    static int order[4096]; int no = 0; static char used[2048]; memset(used, 0, sizeof used);
    for (int f = 0; f < c.n_first; f++)
        for (int i = 0; i < nrows; i++)
            if (!used[i] && (!strcmp(c.first[f], rows[i].key) || !strcmp(c.first[f], rows[i].tid))) { order[no++] = i; used[i] = 1; }
    for (int i = 0; i < nrows; i++) if (!used[i]) order[no++] = i;
    char done_tids[2048][16]; int ndone = 0;
    for (int oi = 0; oi < no; oi++) {
        game_t *gp = &rows[order[oi]], g = *gp;
        if (c.n_only && !listed(c.only, c.n_only, g.key, g.tid)) continue;
        if (listed(c.skip, c.n_skip, g.key, g.tid)) continue;
        int dupe = 0; for (int i = 0; i < ndone; i++) if (!strcmp(done_tids[i], g.tid)) dupe = 1;
        if (dupe) continue;                                         // one starter per title id per pass
        if (tid_present(g.tid)) { present++; strcpy(done_tids[ndone++], g.tid); continue; }
        st_t *s = state_get(g.key);
        int size_refusal = s && !strcmp(s->status, "refused") && !strncmp(s->reason, "starter would be", 16);   // re-checked: free space changes
        if (s && ((!strcmp(s->status, "refused") && !size_refusal) || (!strcmp(s->status, "failed") && s->tries >= MAX_TRIES) || !strcmp(s->status, "done"))) { known++; continue; }
        if (!g.version[0]) { state_set(g.key, "refused", "sce_sys/param.json unreadable (image damaged?)"); refused++; logf_("refused %s: param.json unreadable", g.key); continue; }
        int gfw = fw_hundredths(g.fw);
        if (cfw && gfw > cfw) {
            char r[200]; snprintf(r, sizeof r, "needs FW %s, console is %d.%02d: backport not built on the console yet (phase 2)", g.fw, cfw / 100, cfw % 100);
            state_set(g.key, "refused", r); refused++; logf_("refused %s %s: %s", g.key, g.title, r); continue;
        }
        strcpy(done_tids[ndone++], g.tid);
        char reason[600] = "";
        int rc = build_game(&c, &g, cfw, reason, sizeof reason);
        if (rc == 0) { state_set(g.key, "done", reason); built++; logf_("  done %s -> %s", g.key, reason); tids_in(g.tid); }
        else if (rc == 1) { state_set(g.key, "refused", reason); refused++; logf_("  refused %s %s: %s", g.key, g.title, reason); }
        else { state_set(g.key, "failed", reason); failed++; logf_("  FAILED %s %s (try %d of %d): %s", g.key, g.title, state_get(g.key)->tries, MAX_TRIES, reason); }
    }
    free(txt);
    char dp[600];
    logf_("pass: %d images listed by %s:%d, %d already on the console, %d built, %d refused, %d failed, %d settled earlier (state file); /data free %lld MB",
          listed_n, c.host, c.port, present, built, refused, failed, known, free_mb(P(dp, sizeof dp, "/data")));
    return 0;
}

int main(int argc, char **argv) {
#ifndef __PROSPERO__
    const char *r = getenv("BM_ROOT");
    if (r) snprintf(g_root, sizeof g_root, "%s", r);
#endif
    char p[600];
    makedirs(P(p, sizeof p, "/data/blazing"));
    int lk = open(P(p, sizeof p, LOCK_PATH), O_RDWR | O_CREAT, 0644);
    if (lk >= 0 && flock(lk, LOCK_EX | LOCK_NB) != 0) { logf_("another blazingmountd is running: this one exits"); return 0; }
    logf_("blazingmountd %s start (%s), fork %zu bytes sha256 %s", BM_VERSION, (argc > 1 && !strcmp(argv[1], "once")) ? "once" : "resident",
          (size_t)bm_fork_len, BM_FORK_SHA);
    if (argc > 1 && !strcmp(argv[1], "once")) return sync_once() == 0 ? 0 : 1;
    for (;;) {
        conf_t c; read_conf(&c);
        int rc = sync_once();
        sleep(rc == 0 ? (unsigned)c.poll_secs : 60);                 // host not up yet (boot): try again in a minute
    }
    return 0;
}
