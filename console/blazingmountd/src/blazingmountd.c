// ---------------------------------------------------------------- ampr_emu.index (AMPRIDX3), exactly host/engine/amprindex.build()
typedef struct { const char *path; size_t plen; long long size; size_t blob_off; int order; } ix_t;

static int key_cmp(const char *a, size_t al, const char *b, size_t bl) {
    size_t n = al < bl ? al : bl;
    for (size_t i = 0; i < n; i++) {
        unsigned char x = (unsigned char)a[i], y = (unsigned char)b[i];
        if (x == '\\') x = '/'; if (y == '\\') y = '/';
        if (x >= 'A' && x <= 'Z') x += 32; if (y >= 'A' && y <= 'Z') y += 32;
        if (x != y) return x < y ? -1 : 1;
    }
    return al < bl ? -1 : (al > bl ? 1 : 0);
}
static int ix_cmp(const void *pa, const void *pb) {
    const ix_t *a = pa, *b = pb;
    int c = key_cmp(a->path, a->plen, b->path, b->plen);
    return c ? c : (a->order - b->order);                            // stable, like Python's sort
}
static uint64_t fnv_key(const char *p, size_t n) {
    uint64_t h = 1469598103934665603ULL;
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)p[i];
        if (c == '\\') c = '/';
        if (c >= 'A' && c <= 'Z') c += 32;
        h ^= c; h *= 1099511628211ULL;
    }
    return h ? h : 1;
}
static void put32(unsigned char *b, uint32_t v) { for (int i = 0; i < 4; i++) b[i] = (unsigned char)(v >> (8 * i)); }
static void put64(unsigned char *b, uint64_t v) { for (int i = 0; i < 8; i++) b[i] = (unsigned char)(v >> (8 * i)); }

// paths[i] = "/app0/<rel>" (blob order), sizes[i]; mtime 0. Writes the index to `out`. Returns 0 on success.
static int write_ampr_index(const char *out, char **paths, long long *sizes, int n) {
    ix_t *ix = calloc((size_t)(n ? n : 1), sizeof *ix);
    size_t blob = 0;
    for (int i = 0; i < n; i++) { ix[i].path = paths[i]; ix[i].plen = strlen(paths[i]); ix[i].size = sizes[i]; ix[i].blob_off = blob; ix[i].order = i; blob += ix[i].plen + 1; }
    qsort(ix, (size_t)n, sizeof *ix, ix_cmp);
    uint64_t slots = 2; while (slots < (uint64_t)2 * (uint64_t)n) slots <<= 1;
    size_t path_off = 48 + (size_t)24 * (size_t)n, hash_off = (path_off + blob + 7) & ~(size_t)7;
    size_t total = hash_off + (size_t)slots * 16;
    unsigned char *b = calloc(1, total);
    if (!b) { free(ix); return -1; }
    memcpy(b, "AMPRIDX3", 8); put32(b + 8, 3); put32(b + 12, 24); put64(b + 16, (uint64_t)n); put64(b + 24, blob);
    put64(b + 32, hash_off); put32(b + 40, 16); put32(b + 44, (uint32_t)slots);
    for (int i = 0; i < n; i++) {
        unsigned char *r = b + 48 + 24 * (size_t)i;
        put32(r, (uint32_t)ix[i].blob_off); put32(r + 4, (uint32_t)ix[i].plen); put64(r + 8, (uint64_t)ix[i].size); put64(r + 16, 0);
    }
    for (int i = 0; i < n; i++) memcpy(b + path_off + ix[i].blob_off, ix[i].path, ix[i].plen + 1);
    uint64_t mask = slots - 1;
    for (int i = 0; i < n; i++) {
        uint64_t h = fnv_key(ix[i].path, ix[i].plen), pos = h & mask; int dup = 0;
        for (;;) {
            unsigned char *sl = b + hash_off + pos * 16;
            uint32_t ip1 = (uint32_t)sl[8] | ((uint32_t)sl[9] << 8) | ((uint32_t)sl[10] << 16) | ((uint32_t)sl[11] << 24);
            if (!ip1) break;
            uint64_t sh = 0; for (int k = 7; k >= 0; k--) sh = (sh << 8) | sl[k];
            if (sh == h) { sl[12] |= 1; dup = 1; }
            pos = (pos + 1) & mask;
        }
        unsigned char *sl = b + hash_off + pos * 16;
        put64(sl, h); put32(sl + 8, (uint32_t)i + 1); put32(sl + 12, dup ? 1 : 0);
    }
    int r = write_file(out, b, total);
    free(b); free(ix);
    return r;
}

// ---------------------------------------------------------------- one game
typedef struct { char *path; long long size; int remote; } gf_t;

static int ends_with(const char *s, const char *suf, int nocase) {
    size_t a = strlen(s), b = strlen(suf);
    if (b > a) return 0;
    return nocase ? !strcasecmp(s + a - b, suf) : !strcmp(s + a - b, suf);
}
static int starts(const char *s, const char *p) { return !strncmp(s, p, strlen(p)); }

// mkgame.KEEP_LOCAL_EXT (case as mkgame) + blazingmount-starter.MODULE_EXT (any case)
static int keep_local(const char *p) {
    static const char *ext[] = { ".pgm", ".prx", ".sprx", ".elf", ".self", ".index", ".crc", ".cache", ".utoc", 0 };   // = mkgame 24 Oct
    static const char *mod[] = { ".prx", ".sprx", ".elf", ".self", 0 };
    for (int i = 0; ext[i]; i++) if (ends_with(p, ext[i], 0)) return 1;
    for (int i = 0; mod[i]; i++) if (ends_with(p, mod[i], 1)) return 1;
    return 0;
}

static int remote_cmp(const void *a, const void *b) {               // size desc, then list order (stable)
    const gf_t *x = *(gf_t *const *)a, *y = *(gf_t *const *)b;
    if (x->size != y->size) return x->size > y->size ? -1 : 1;
    return x < y ? -1 : (x > y);
}

static int file_has(const char *path, const char *needle) {
    int fd = open(path, O_RDONLY); if (fd < 0) return 0;
    static char b[1 << 20]; size_t nl = strlen(needle), keep = 0; int hit = 0;
    for (;;) {
        ssize_t n = read(fd, b + keep, sizeof b - keep);
        if (n <= 0) break;
        size_t len = keep + (size_t)n;
        for (size_t i = 0; i + nl <= len; i++) if (b[i] == needle[0] && !memcmp(b + i, needle, nl)) { hit = 1; break; }
        if (hit) break;
        keep = nl - 1 < len ? nl - 1 : len;
        memmove(b, b + len - keep, keep);
    }
    close(fd);
    return hit;
}

static int fetch_to(const conf_t *c, const char *key, const char *rel, const char *dst, long long want) {
    char url[2200]; snprintf(url, sizeof url, "/t/%s/%s", key, rel);
    for (int t = 1; t <= 3; t++) {
        parent_dirs(dst);
        int fd = open_out(dst);
        if (fd < 0) { logf_("  cannot create %s (errno %d)", dst, errno); return -1; }
        int st = 0;
        long long n = http_get(c->host, c->port, url, fd, NULL, 60, &st);
        close(fd);
        if (n == want) return 0;
        logf_("  fetch %s try %d: got %lld of %lld bytes (http %d)", rel, t, n, want, st);
        sleep(2 * t);
    }
    return -1;
}

typedef struct { char key[48], tid[16], version[32], fw[16], title[256]; long long size; } game_t;

// Builds one starter. Returns 0 done, 1 refused (reason), -1 failed (reason).
static int game_running(const char *tid);
static int build_game(const conf_t *c, const game_t *g, int cfw, char *reason, size_t rn, int replace) {
    char name[400], title[300];
    snprintf(title, sizeof title, "%s", g->title[0] ? g->title : g->tid);
    {   // mkgame: name.replace("/", " ").replace(":", "").strip()
        char t2[300]; size_t o = 0;
        for (const char *q = title; *q && o + 1 < sizeof t2; q++) { if (*q == ':') continue; t2[o++] = (*q == '/') ? ' ' : *q; }
        t2[o] = 0;
        char *s = t2; while (*s == ' ' || *s == '\t') s++;
        size_t L = strlen(s); while (L && (s[L - 1] == ' ' || s[L - 1] == '\t')) s[--L] = 0;
        snprintf(name, sizeof name, "%s (%s)", s, g->tid);
    }
    char dest[900], hb[600]; snprintf(dest, sizeof dest, "%s/%s", P(hb, sizeof hb, c->homebrew_dir), name);
    if (exists(dest) && !replace) { snprintf(reason, rn, "folder already there"); return 0; }

    // 1) the file list
    char url[200], *lst = NULL; int st = 0;
    snprintf(url, sizeof url, "/f/%s", g->key);
    long long ln = http_get(c->host, c->port, url, -1, &lst, 300, &st);
    if (ln < 0) { snprintf(reason, rn, "file list %s failed (http %d)", url, st); return -1; }
    int cap = 1024, n = 0; gf_t *f = malloc(sizeof *f * (size_t)cap);
    char *save = NULL;
    for (char *l = strtok_r(lst, "\n", &save); l; l = strtok_r(NULL, "\n", &save)) {
        char *tab = strchr(l, '\t'); if (!tab) continue;
        *tab = 0;
        if (starts(tab + 1, "decrypted/")) continue;                 // mkgame skips the dumper's decrypted/ copies
        if (n == cap) { cap *= 2; f = realloc(f, sizeof *f * (size_t)cap); }
        f[n].size = atoll(l); f[n].path = tab + 1; f[n].remote = 0; n++;
    }
    // 2) which files stream: >= 1 MiB, not eboot.bin / sce_sys/ / sce_module/ / prx/ / fakelib*, not a keep-local type; largest first
    gf_t **big = malloc(sizeof *big * (size_t)(n ? n : 1)); int nb = 0, has_index = 0, has_eboot = 0;
    long long total = 0;
    for (int i = 0; i < n; i++) {
        total += f[i].size;
        if (!strcmp(f[i].path, "ampr_emu.index")) has_index = 1;
        if (!strcmp(f[i].path, "eboot.bin")) has_eboot = 1;
        if (f[i].size >= MIN_REMOTE_BYTES && strcmp(f[i].path, "eboot.bin") && !starts(f[i].path, "sce_sys/") && !starts(f[i].path, "sce_module/")
            && !starts(f[i].path, "prx/") && !starts(f[i].path, "fakelib") && !keep_local(f[i].path)) big[nb++] = &f[i];
    }
    qsort(big, (size_t)nb, sizeof *big, remote_cmp);
    int nr = nb < MAX_REMOTE ? nb : MAX_REMOTE;
    long long remote_bytes = 0;
    for (int i = 0; i < nr; i++) { big[i]->remote = 1; remote_bytes += big[i]->size; }
    long long starter_bytes = total - remote_bytes;
    int rc = -1;
    char stage[900], sp[600];
    char par[300], pp[600];
    {   // stage on the same drive as the homebrew dir: <parent of homebrew_dir>/blz-stage/bm (= /data/blz-stage/bm by default)
        snprintf(par, sizeof par, "%s", c->homebrew_dir);
        char *sl = strrchr(par, '/'); if (sl && sl != par) *sl = 0; else strcpy(par, "/data");
        char sd[400]; snprintf(sd, sizeof sd, "%s/blz-stage/bm", par);
        snprintf(stage, sizeof stage, "%s/%s", P(sp, sizeof sp, sd), name);
    }
    if (!has_eboot) { snprintf(reason, rn, "no eboot.bin in the image"); rc = 1; goto out; }
    long long fm = free_mb(P(pp, sizeof pp, par));                // the drive the starter lands on (the homebrew dir's parent exists)
    long long scap = c->max_starter_mb;                               // a bigger starter is fine on a console with lots of room
    if (scap > 0 && c->big_starter_mb > scap && fm >= c->big_free_mb) scap = c->big_starter_mb;
    if (scap > 0 && starter_bytes > scap * 1000000LL) {
        snprintf(reason, rn, "starter would be %.1f GB (limit %lld MB with %lld MB free on /data; %lld MB when >= %lld MB free)",
                 starter_bytes / 1e9, scap, fm, c->big_starter_mb, c->big_free_mb);
        rc = 1; goto out;
    }
    if (fm >= 0 && fm - starter_bytes / (1024 * 1024) < c->min_free_mb) {
        snprintf(reason, rn, "not enough space: %lld MB free, starter %lld MB, floor %lld MB", fm, starter_bytes / (1024 * 1024), c->min_free_mb);
        rc = -1; goto out;
    }
    logf_("build %s [%s] v%s FW %s: %d files, %d streamed (%.1f GB), starter %.2f GB (cap %lld MB, /data free %lld MB), %s", name, g->key, g->version, g->fw, n, nr,
          remote_bytes / 1e9, starter_bytes / 1e9, scap, fm, has_index ? "own ampr_emu.index" : "ampr_emu.index made here");

    // 3) stage: eboot first (fail fast when the game cannot stream), then everything else
    rm_rf(stage);
    makedirs(stage);
    char dst[2400];
    snprintf(dst, sizeof dst, "%s/eboot.bin", stage);
    long long eb = 0; for (int i = 0; i < n; i++) if (!strcmp(f[i].path, "eboot.bin")) eb = f[i].size;
    if (fetch_to(c, g->key, "eboot.bin", dst, eb) != 0) { snprintf(reason, rn, "eboot.bin download failed"); goto out; }
    if (!file_has(dst, "libSceAmpr.prx")) {
        snprintf(reason, rn, "CANNOT STREAM: the eboot does not load libSceAmpr, so our link never runs in this game"); rc = 1; goto out;
    }
    long long got = 0; int nfiles = 0;
    for (int i = 0; i < n; i++) {
        if (!strcmp(f[i].path, "eboot.bin") || starts(f[i].path, "fakelib/")) continue;
        snprintf(dst, sizeof dst, "%s/%s", stage, f[i].path);
        if (f[i].remote) { parent_dirs(dst); if (write_file(dst, "", 0) != 0) { snprintf(reason, rn, "cannot create %s", f[i].path); goto out; } continue; }
        if (fetch_to(c, g->key, f[i].path, dst, f[i].size) != 0) { snprintf(reason, rn, "download failed: %s", f[i].path); goto out; }
        got += f[i].size; nfiles++;
        if (nfiles % 5000 == 0) logf_("  %d files, %.2f GB so far", nfiles, got / 1e9);
    }
    // 4) ampr_emu.index with the real sizes when the game has none
    if (!has_index) {
        char **pp = malloc(sizeof *pp * (size_t)(n ? n : 1)); long long *ss = malloc(sizeof *ss * (size_t)(n ? n : 1)); int k = 0;
        for (int i = 0; i < n; i++) {
            if (starts(f[i].path, "fakelib/")) continue;
            size_t L = strlen(f[i].path) + 7; pp[k] = malloc(L); snprintf(pp[k], L, "/app0/%s", f[i].path); ss[k] = f[i].size; k++;
        }
        snprintf(dst, sizeof dst, "%s/ampr_emu.index", stage);
        int r = write_ampr_index(dst, pp, ss, k);
        for (int i = 0; i < k; i++) free(pp[i]);
        free(pp); free(ss);
        if (r != 0) { snprintf(reason, rn, "cannot write ampr_emu.index"); goto out; }
    }
    // 5) fakelib: our embedded fork as libSceAmpr.sprx + the game's own fakelib files (flattened, minus its libSceAmpr)
    snprintf(dst, sizeof dst, "%s/fakelib/libSceAmpr.sprx", stage);
    if (write_file(dst, bm_fork, bm_fork_len) != 0) { snprintf(reason, rn, "cannot write the fork"); goto out; }
    for (int i = 0; i < n; i++) {
        if (!starts(f[i].path, "fakelib/")) continue;
        const char *base = strrchr(f[i].path, '/') + 1;
        if (!strcmp(base, "libSceAmpr.sprx")) continue;
        snprintf(dst, sizeof dst, "%s/fakelib/%s", stage, base);
        if (fetch_to(c, g->key, f[i].path, dst, f[i].size) != 0) { snprintf(reason, rn, "download failed: %s", f[i].path); goto out; }
    }
    // 6) the link config, BEFORE the folder appears (ShadowMount may register the tile at once)
    {
        long long dc = c->disk_cache_mb;                              // fixed cap, never sized from the game: see read_conf
        if (dc > 0 && (fm < c->big_free_mb || fm - dc < c->min_free_mb)) {
            logf_("  disk cache off for this game: /data has %lld MB free (needs >= %lld MB and %lld MB left after the %lld MB cache)",
                  fm, c->big_free_mb, c->min_free_mb, dc);
            dc = 0;
        }
        size_t cap2 = 4096 + (size_t)nr * 300; char *cfg = malloc(cap2); size_t o = 0;
        o += (size_t)snprintf(cfg + o, cap2 - o, "# blazingmountd %s v%s: %s, %d files read from %s (%.1f GB)\nmode remote\nserver %s %d\n",
                              BM_VERSION, g->version, name, nr, c->host, remote_bytes / 1e9, c->host, c->port);
        if (g_px_port && g_ts_port)                                   // = mkgame (24 Oct): away-from-home fallback lines right after server
            o += (size_t)snprintf(cfg + o, cap2 - o, "proxy %s %d\nserver_ts %s %d\n", g_px_host, g_px_port, g_ts_host, g_ts_port);
        o += (size_t)snprintf(cfg + o, cap2 - o, "base /t/%s\n", g->key);
        for (int i = 0; i < nr; i++) o += (size_t)snprintf(cfg + o, cap2 - o, "file %lld %s\n", big[i]->size, big[i]->path);
        // same keys and order as mkgame.cfg_text (24 Oct): dc_queue only when not the link's default 16 (we never set it)
        o += (size_t)snprintf(cfg + o, cap2 - o, "block_kb 256\ncache_mb %d\nconns %d\nasync 1\ntimeout_ms 8000\nstats_s 2\nlog_first 60\n"
                              "trace_opens 100\ntrace_io 60\ntrace_apr 60\n", c->cache_mb_ram, c->conns);
        if (dc > 0) o += (size_t)snprintf(cfg + o, cap2 - o, "disk_cache_mb %lld\n", dc);
        if (c->readahead_kb > 0) o += (size_t)snprintf(cfg + o, cap2 - o, "readahead_kb %d\n", c->readahead_kb);
        char lp[600], cfgp[700], tmp[720];
        snprintf(cfgp, sizeof cfgp, "%s/%s.cfg", P(lp, sizeof lp, LINK_DIR), g->tid);
        snprintf(tmp, sizeof tmp, "%s.tmp", cfgp);
        makedirs(lp);
        int w = write_file(tmp, cfg, o);
        free(cfg);
        if (w != 0 || rename(tmp, cfgp) != 0) { snprintf(reason, rn, "cannot write %s (errno %d)", cfgp, errno); goto out; }
    }
    // 7) into the scanned homebrew dir. replace (the image changed): the old starter stays until the new one is complete, and the swap
    //    happens only while the game is not running; the old one is removed after the new one is in place.
    makedirs(hb);
    if (replace && exists(dest)) {
        if (game_running(g->tid)) { snprintf(reason, rn, "game is running: the new starter is not swapped in now (next pass)"); goto out; }
        char old[1000]; snprintf(old, sizeof old, "%s.blz-old", stage);
        rm_rf(old);
        if (rename(dest, old) != 0) { snprintf(reason, rn, "cannot move the old starter aside (errno %d)", errno); goto out; }
        if (rename(stage, dest) != 0) { rename(old, dest); snprintf(reason, rn, "swap failed (errno %d): old starter put back", errno); goto out; }
        rm_rf(old);
    } else if (rename(stage, dest) != 0) { snprintf(reason, rn, "move into %s failed (errno %d)", dest, errno); goto out; }
    snprintf(reason, rn, "%s: %d files local (%.2f GB), %d streamed (%.1f GB), fork %.12s", name, nfiles + 1, starter_bytes / 1e9, nr,
             remote_bytes / 1e9, BM_FORK_SHA);
    rc = 0;
out:
    if (rc != 0) rm_rf(stage);                                       // never leave half a starter behind
    free(big); free(f); free(lst);
    (void)cfw;
    return rc;
}

// ---------------------------------------------------------------- ShadowMount+ version guard (23 Oct 2026)
// DIGI5's payload-manager repo slot pulled ShadowMount+ 1.7beta7 after a wipe and every starter then died the second it launched
// (sandbox released, no game process). The proven build is 1.7beta6-fix2. Its first log line says
// "ShadowMount+ v<version> ...": compare it every pass and say so loudly (log + klog) whenever it is not the expected one.
static void check_smp(const conf_t *c) {
    static char last[64] = "";
    char p[600], b[512] = ""; int fd = open(P(p, sizeof p, SMP_LOG), O_RDONLY);
    char ver[64] = "unknown (no ShadowMount+ log)";
    if (fd >= 0) {
        ssize_t n = read(fd, b, sizeof b - 1); close(fd);
        if (n > 0) {
            b[n] = 0;
            char *v = strstr(b, "ShadowMount+ v");
            if (v) { v += 14; size_t k = 0; while (v[k] && v[k] != ' ' && v[k] != '\n' && k < sizeof ver - 1) { ver[k] = v[k]; k++; } ver[k] = 0; }
            else snprintf(ver, sizeof ver, "unknown (no version line)");
        }
    }
    int ok = !strcmp(ver, c->smp_version);
    if (strcmp(ver, last) || !ok) {
        if (ok) logf_("ShadowMount+ v%s = the proven build", ver);
        else logf_("WARNING: ShadowMount+ v%s is running, expected v%s - starters may die at launch (restore the proven build in the payload-manager slot)", ver, c->smp_version);
        snprintf(last, sizeof last, "%s", ver);
    }
}

// the tsnet proxy for this pass: mount.conf "proxy", else /data/tailscale/config.json "httpProxyAddr": "ip:port"; none = LAN only
static void tsnet_setup(const conf_t *c) {
    static char said[160] = "";
    g_px_port = 0; g_ts_port = 0;
    if (!c->tsnet) return;
    char px[64] = ""; int pp = 0;
    if (c->proxy_port) { snprintf(px, sizeof px, "%s", c->proxy); pp = c->proxy_port; }
    else {
        char p[600], b[8192]; int fd = open(P(p, sizeof p, TSNET_CONF), O_RDONLY);
        if (fd >= 0) {
            ssize_t n = read(fd, b, sizeof b - 1); close(fd);
            if (n > 0) {
                b[n] = 0;
                char *k = strstr(b, "\"httpProxyAddr\"");
                if (k && (k = strchr(k + 15, ':')) && (k = strchr(k, '"'))) {
                    char addr[80] = ""; sscanf(k + 1, "%79[^\"]", addr);
                    char *colon = strrchr(addr, ':');
                    if (colon) { *colon = 0; snprintf(px, sizeof px, "%s", addr[0] ? addr : "127.0.0.1"); pp = atoi(colon + 1); }
                }
            }
        }
    }
    if (pp <= 0) return;
    snprintf(g_px_host, sizeof g_px_host, "%s", strcmp(px, "0.0.0.0") && strcmp(px, "localhost") ? px : "127.0.0.1");
    g_px_port = pp;
    snprintf(g_ts_host, sizeof g_ts_host, "%s", c->server_ts);
    g_ts_port = c->server_ts_port ? c->server_ts_port : c->port;
    char now[160]; snprintf(now, sizeof now, "%s:%d %s:%d", g_px_host, g_px_port, g_ts_host, g_ts_port);
    if (strcmp(now, said)) { logf_("tsnet: away-from-home fallback ready (proxy %s:%d -> %s:%d)", g_px_host, g_px_port, g_ts_host, g_ts_port); snprintf(said, sizeof said, "%s", now); }
}

// ---------------------------------------------------------------- auto-update (v2.5, Markus 24 Oct: "it should have been installed on both")
// A game counts as running while ShellCore has its sandbox (/mnt/sandbox/<TID>_000; a leftover sandbox only delays an update).
static int game_running(const char *tid) {
    char p[600], s2[64]; snprintf(s2, sizeof s2, "/mnt/sandbox/%s_000", tid);
    return exists(P(p, sizeof p, s2));
}

static char *slurp(const char *path, size_t *len) {
    int fd = open(path, O_RDONLY); if (fd < 0) return NULL;
    struct stat sb; if (fstat(fd, &sb) != 0) { close(fd); return NULL; }
    char *b = malloc((size_t)sb.st_size + 1); if (!b) { close(fd); return NULL; }
    size_t got = 0; ssize_t n;
    while (got < (size_t)sb.st_size && (n = read(fd, b + got, (size_t)sb.st_size - got)) > 0) got += (size_t)n;
    close(fd); b[got] = 0; *len = got;
    return b;
}

static int mem_has(const char *b, size_t n, const char *needle) {
    size_t k = strlen(needle);
    for (size_t i = 0; i + k <= n; i++) if (b[i] == needle[0] && !memcmp(b + i, needle, k)) return 1;
    return 0;
}

// The link settings this payload manages in ANY streaming starter's cfg: conns, readahead_kb, proxy, server_ts (the file list, base,
// cache and trace lines stay as they are: a hand-made or backported starter keeps its own). Returns a malloc'd new cfg text, or NULL
// when nothing would change.
static char *patched_cfg(const conf_t *c, const char *old, size_t olen) {
    size_t cap = olen + 512; char *o = malloc(cap); size_t n = 0;
    const char *p = old, *end = old + olen;
    while (p < end) {
        const char *e = memchr(p, '\n', (size_t)(end - p)); if (!e) e = end;
        size_t L = (size_t)(e - p);
        int drop = (L >= 6 && !strncmp(p, "conns ", 6)) || (L >= 13 && !strncmp(p, "readahead_kb ", 13)) ||
                   (L >= 6 && !strncmp(p, "proxy ", 6)) || (L >= 10 && !strncmp(p, "server_ts ", 10));
        if (!drop) {
            memcpy(o + n, p, L); n += L; o[n++] = '\n';
            if (L >= 7 && !strncmp(p, "server ", 7) && g_px_port && g_ts_port)
                n += (size_t)snprintf(o + n, cap - n, "proxy %s %d\nserver_ts %s %d\n", g_px_host, g_px_port, g_ts_host, g_ts_port);
        }
        p = e < end ? e + 1 : end;
    }
    n += (size_t)snprintf(o + n, cap - n, "conns %d\n", c->conns);
    if (c->readahead_kb > 0) n += (size_t)snprintf(o + n, cap - n, "readahead_kb %d\n", c->readahead_kb);
    o[n] = 0;
    // same settings (in any order) = no change: compare as sorted sets of the managed lines
    size_t on = 0, nn = 0; char ob[2048] = "", nb[2048] = "";
    for (int pass = 0; pass < 2; pass++) {
        const char *q = pass ? o : old, *qe = pass ? o + n : end; char *dst = pass ? nb : ob; size_t *dn = pass ? &nn : &on;
        while (q < qe) {
            const char *e = memchr(q, '\n', (size_t)(qe - q)); if (!e) e = qe;
            size_t L = (size_t)(e - q);
            if (((L >= 6 && (!strncmp(q, "conns ", 6) || !strncmp(q, "proxy ", 6))) || (L >= 13 && !strncmp(q, "readahead_kb ", 13)) ||
                 (L >= 10 && !strncmp(q, "server_ts ", 10))) && *dn + L + 2 < 2048) { memcpy(dst + *dn, q, L); *dn += L; dst[(*dn)++] = '|'; dst[*dn] = 0; }
            q = e < qe ? e + 1 : qe;
        }
    }
    if (!strcmp(ob, nb)) { free(o); return NULL; }
    return o;
}

// Keep ONE present streaming starter current. Never for a running game, a pinned folder, a starter that is not a streaming one (no
// "mode remote" cfg) or one whose libSceAmpr is not our link (a full copy, a stock emulator): those are left exactly as they are.
//   fork:  fakelib/libSceAmpr.sprx differs from the fork inside this payload -> replaced (new file next to it, then one rename)
//   cfg:   the managed settings differ (patched_cfg) -> rewritten (tmp + rename), only once the starter has our current fork
// Returns 1 when something was updated.
static int update_starter(const conf_t *c, const char *tid, const char *dir) {
    if (!c->auto_update || !dir) return 0;
    char p1[900], p2[900], cfgp[700], lp[600];
    snprintf(p1, sizeof p1, "%s/.blazingmount-pin", dir); if (exists(p1)) return 0;
    snprintf(cfgp, sizeof cfgp, "%s/%s.cfg", P(lp, sizeof lp, LINK_DIR), tid);
    size_t clen = 0; char *cfg = slurp(cfgp, &clen);
    if (!cfg) return 0;
    if (!mem_has(cfg, clen, "\nmode remote")) { free(cfg); return 0; }
    {   // must BE a starter: the cfg's first streamed file is a 0-byte placeholder in this folder (a full copy has the real bytes)
        const char *fl = strstr(cfg, "\nfile ");
        long long want = 0; char rel[700] = "";
        if (!fl || sscanf(fl + 6, "%lld %699[^\n]", &want, rel) != 2 || want <= 0) { free(cfg); return 0; }
        char fp[1500]; struct stat sb; snprintf(fp, sizeof fp, "%s/%s", dir, rel);
        if (stat(fp, &sb) != 0 || sb.st_size != 0) { free(cfg); return 0; }
    }
    snprintf(p1, sizeof p1, "%s/fakelib/libSceAmpr.sprx", dir);
    size_t flen = 0; char *fk = slurp(p1, &flen);
    if (!fk || !mem_has(fk, flen, "blz_link")) { free(fk); free(cfg); return 0; }     // not our link: leave it
    int fork_same = flen == bm_fork_len && !memcmp(fk, bm_fork, flen);
    free(fk);
    char *ncfg = patched_cfg(c, cfg, clen);
    if (fork_same && !ncfg) { free(cfg); return 0; }
    if (game_running(tid)) { logf_("  update %s waits: the game is running", tid); free(ncfg); free(cfg); return 0; }
    if (!fork_same) {
        snprintf(p2, sizeof p2, "%s/fakelib/libSceAmpr.blz-new.sprx", dir);   // ends in .sprx: written 0755 like every module (CE-108255-1 otherwise)
        if (write_file(p2, bm_fork, bm_fork_len) != 0 || rename(p2, p1) != 0) { logf_("  update %s: cannot replace the fork (errno %d)", tid, errno); unlink(p2); free(ncfg); free(cfg); return 0; }
        logf_("  updated %s: fork -> %.12s (%s)", tid, BM_FORK_SHA, dir);
    }
    if (ncfg) {
        char tmp[720]; snprintf(tmp, sizeof tmp, "%s.tmp", cfgp);
        if (write_file(tmp, ncfg, strlen(ncfg)) != 0 || rename(tmp, cfgp) != 0) logf_("  update %s: cannot rewrite the cfg (errno %d)", tid, errno);
        else logf_("  updated %s: link settings (conns %d, readahead_kb %d%s)", tid, c->conns, c->readahead_kb, g_px_port ? ", tsnet proxy" : "");
    }
    free(ncfg); free(cfg);
    return 1;
}

#include "bm_api.c"           // the app's local API (:8094): reads + queued actions, applied in sync_once by the one writer

// ---------------------------------------------------------------- one pass over the host's games
static int sync_once(void) {
    conf_t c; read_conf(&c);
    bm_api_pass_begin(&c);                                       // the app's queued actions + its choices (bm_api.c)
    check_smp(&c);
    tsnet_setup(&c);
    int cfw = console_fw(&c);
    char *txt = NULL; int st = 0;
    long long n = http_get(c.host, c.port, "/games.txt", -1, &txt, 300, &st);
    if (n < 0) { logf_("games list http://%s:%d/games.txt failed (http %d)", c.host, c.port, st); return -1; }
    state_load();
    scan_present();
    int listed_n = 0, present = 0, built = 0, refused = 0, failed = 0, known = 0, updated = 0;
    static game_t rows[2048]; int nrows = 0;
    char *save = NULL;
    for (char *l = strtok_r(txt, "\n", &save); l && nrows < 2048; l = strtok_r(NULL, "\n", &save)) {
        if (l[0] == '#' || !l[0]) continue;
        char *fld[7] = {0}; int k = 0; char *q = l; fld[k++] = q;
        while (*q && k < 7) { if (*q == '\t') { *q = 0; fld[k++] = q + 1; } q++; }
        if (k < 7) continue;
        game_t *g = &rows[nrows++]; memset(g, 0, sizeof *g);
        snprintf(g->key, sizeof g->key, "%s", fld[0]); snprintf(g->tid, sizeof g->tid, "%s", fld[1]); g->size = atoll(fld[2]);
        snprintf(g->version, sizeof g->version, "%s", fld[3]); snprintf(g->fw, sizeof g->fw, "%s", fld[4]);
        snprintf(g->title, sizeof g->title, "%s", fld[6]);
        char *cr = strchr(g->title, '\r'); if (cr) *cr = 0;
    }
    listed_n = nrows;
    // the order: every 'first' entry (in mount.conf order), then the rest in the host's order
    static int order[4096]; int no = 0; static char used[2048]; memset(used, 0, sizeof used);
    for (int f = 0; f < c.n_first; f++)
        for (int i = 0; i < nrows; i++)
            if (!used[i] && (!strcmp(c.first[f], rows[i].key) || !strcmp(c.first[f], rows[i].tid))) { order[no++] = i; used[i] = 1; }
    for (int i = 0; i < nrows; i++) if (!used[i]) order[no++] = i;
    char done_tids[2048][16]; int ndone = 0;
    for (int oi = 0; oi < no; oi++) {
        game_t *gp = &rows[order[oi]], g = *gp;
        if (c.n_only && !listed(c.only, c.n_only, g.key, g.tid)) continue;
        if (listed(c.skip, c.n_skip, g.key, g.tid)) continue;
        int dupe = 0; for (int i = 0; i < ndone; i++) if (!strcmp(done_tids[i], g.tid)) dupe = 1;
        if (dupe) continue;                                         // one starter per title id per pass
        if (tid_present(g.tid)) {
            present++; strcpy(done_tids[ndone++], g.tid);
            // built by this payload from another image of the same title id = the image on the drive changed: rebuild + safe swap
            int ours_other = 0;
            for (int i = 0; i < g_nst; i++) {
                if (strcmp(g_st[i].status, "done") || strncmp(g_st[i].key, g.tid, 9) || g_st[i].key[9] != '@' || !strcmp(g_st[i].key, g.key)) continue;
                int still = 0;                                        // a second image of the title still on the drives is NOT a change
                for (int r = 0; r < nrows; r++) if (!strcmp(rows[r].key, g_st[i].key)) still = 1;
                if (!still) ours_other = i + 1;
            }
            if (c.auto_update && ours_other && !(state_get(g.key) && !strcmp(state_get(g.key)->status, "failed") && state_get(g.key)->tries >= MAX_TRIES)) {
                logf_("image changed for %s: %s -> %s, rebuilding the starter", g.tid, g_st[ours_other - 1].key, g.key);
                char reason[600] = "";
                bm_api_busy(g.tid, g.title);
                int rc = build_game(&c, &g, cfw, reason, sizeof reason, 1);
                bm_api_busy(NULL, NULL);
                if (rc == 0) { state_set(g.key, "done", reason); state_set(g_st[ours_other - 1].key, "replaced", g.key); built++; logf_("  done %s -> %s", g.key, reason); }
                else if (rc == 1) { state_set(g.key, "refused", reason); refused++; logf_("  refused %s: %s", g.key, reason); }
                else { state_set(g.key, "failed", reason); failed++; logf_("  FAILED %s (try %d of %d): %s", g.key, state_get(g.key)->tries, MAX_TRIES, reason); }
            } else if (update_starter(&c, g.tid, tid_dir(g.tid))) updated++;
            continue;
        }
        st_t *s = state_get(g.key);
        int size_refusal = s && !strcmp(s->status, "refused") && !strncmp(s->reason, "starter would be", 16);   // re-checked: free space changes
        if (s && ((!strcmp(s->status, "refused") && !size_refusal) || (!strcmp(s->status, "failed") && s->tries >= MAX_TRIES) || !strcmp(s->status, "done"))) { known++; continue; }
        if (!g.version[0]) { state_set(g.key, "refused", "sce_sys/param.json unreadable (image damaged?)"); refused++; logf_("refused %s: param.json unreadable", g.key); continue; }
        int gfw = fw_hundredths(g.fw);
        if (cfw && gfw > cfw) {
            char r[200]; snprintf(r, sizeof r, "needs FW %s, console is %d.%02d: backport not built on the console yet (phase 2)", g.fw, cfw / 100, cfw % 100);
            state_set(g.key, "refused", r); refused++; logf_("refused %s %s: %s", g.key, g.title, r); continue;
        }
        strcpy(done_tids[ndone++], g.tid);
        char reason[600] = "";
        bm_api_busy(g.tid, g.title);
        int rc = build_game(&c, &g, cfw, reason, sizeof reason, 0);
        bm_api_busy(NULL, NULL);
        if (rc == 0) { state_set(g.key, "done", reason); built++; logf_("  done %s -> %s", g.key, reason); tids_in(g.tid); }
        else if (rc == 1) { state_set(g.key, "refused", reason); refused++; logf_("  refused %s %s: %s", g.key, g.title, reason); }
        else { state_set(g.key, "failed", reason); failed++; logf_("  FAILED %s %s (try %d of %d): %s", g.key, g.title, state_get(g.key)->tries, MAX_TRIES, reason); }
    }
    free(txt);
    char dp[600];
    logf_("pass: %d images listed by %s:%d, %d already on the console (%d updated), %d built, %d refused, %d failed, %d settled earlier (state file); /data free %lld MB",
          listed_n, c.host, c.port, present, updated, built, refused, failed, known, free_mb(P(dp, sizeof dp, "/data")));
    return 0;
}

int main(int argc, char **argv) {
#ifndef __PROSPERO__
    const char *r = getenv("BM_ROOT");
    if (r) snprintf(g_root, sizeof g_root, "%s", r);
#endif
    char p[600];
    makedirs(P(p, sizeof p, "/data/blazing"));
    int lk = open(P(p, sizeof p, LOCK_PATH), O_RDWR | O_CREAT, 0644);
    if (lk >= 0 && flock(lk, LOCK_EX | LOCK_NB) != 0) { logf_("another blazingmountd is running: this one exits"); return 0; }
    logf_("blazingmountd %s start (%s) pid %d, fork %zu bytes sha256 %s", BM_VERSION, (argc > 1 && !strcmp(argv[1], "once")) ? "once" : "resident",
          (int)getpid(), (size_t)bm_fork_len, BM_FORK_SHA);
    {   // pid file: an update can stop exactly this process (pldmgr process_kill) instead of guessing among "payload.elf" entries
        char pp[600], pb[32]; int n = snprintf(pb, sizeof pb, "%d\n", (int)getpid());
        write_file(P(pp, sizeof pp, "/data/blazing/blazingmountd.pid"), pb, (size_t)n);
    }
    if (argc > 1 && !strcmp(argv[1], "once")) return sync_once() == 0 ? 0 : 1;
    bm_api_start();                                                  // the app's API thread (bm_api.c)
    for (;;) {
        conf_t c; read_conf(&c);
        int rc = sync_once();
        bm_api_wait(rc == 0 ? c.poll_secs : 60);                     // host not up yet (boot): a minute; early when the app asks or the drives change
    }
    return 0;
}
